# Proto Compilation Script for Legal AI Platform
# Generates TypeScript and Go bindings from protobuf definitions
param(
    [string]$Target = "all",  # Options: all, typescript, go
    [switch]$Verbose
)

$ErrorActionPreference = "Stop"

Write-Host "🚀 Legal AI Proto Compilation Script" -ForegroundColor Green
Write-Host "Target: $Target" -ForegroundColor Cyan

# Paths
$ProtoDir = Join-Path $PSScriptRoot "..\proto"
$OutputDir = Join-Path $PSScriptRoot "..\generated"
$TsOutputDir = Join-Path $OutputDir "typescript"
$GoOutputDir = Join-Path $OutputDir "go"

# Create output directories
@($OutputDir, $TsOutputDir, $GoOutputDir) | ForEach-Object {
    if (-not (Test-Path $_)) {
        New-Item -ItemType Directory -Path $_ -Force | Out-Null
        Write-Host "✅ Created directory: $_" -ForegroundColor Green
    }
}

# Proto files to compile
$ProtoFiles = @(
    "ingest.proto",
    "embedding.proto", 
    "legal_services.proto"
)

function Test-Prerequisites {
    Write-Host "🔍 Checking prerequisites..." -ForegroundColor Yellow
    
    # Check protoc
    try {
        $protocVersion = & protoc --version
        Write-Host "✅ protoc found: $protocVersion" -ForegroundColor Green
    } catch {
        Write-Host "❌ protoc not found. Install Protocol Buffers compiler." -ForegroundColor Red
        Write-Host "   Download from: https://github.com/protocolbuffers/protobuf/releases" -ForegroundColor Yellow
        exit 1
    }
    
    # Check protoc-gen-ts (for TypeScript)
    if ($Target -eq "all" -or $Target -eq "typescript") {
        try {
            $tsGenVersion = & protoc-gen-ts --version 2>$null
            Write-Host "✅ protoc-gen-ts found: $tsGenVersion" -ForegroundColor Green
        } catch {
            Write-Host "❌ protoc-gen-ts not found. Installing via npm..." -ForegroundColor Yellow
            try {
                & npm install -g protoc-gen-ts
                Write-Host "✅ protoc-gen-ts installed" -ForegroundColor Green
            } catch {
                Write-Host "❌ Failed to install protoc-gen-ts" -ForegroundColor Red
                exit 1
            }
        }
    }
    
    # Check protoc-gen-go (for Go)
    if ($Target -eq "all" -or $Target -eq "go") {
        try {
            & protoc-gen-go --version | Out-Null
            Write-Host "✅ protoc-gen-go found" -ForegroundColor Green
        } catch {
            Write-Host "❌ protoc-gen-go not found. Install with:" -ForegroundColor Red
            Write-Host "   go install google.golang.org/protobuf/cmd/protoc-gen-go@latest" -ForegroundColor Yellow
            Write-Host "   go install google.golang.org/grpc/cmd/protoc-gen-go-grpc@latest" -ForegroundColor Yellow
        }
    }
}

function Compile-TypeScript {
    Write-Host "📦 Compiling TypeScript bindings..." -ForegroundColor Blue
    
    foreach ($proto in $ProtoFiles) {
        $protoPath = Join-Path $ProtoDir $proto
        
        if (-not (Test-Path $protoPath)) {
            Write-Host "⚠️  Proto file not found: $protoPath" -ForegroundColor Yellow
            continue
        }
        
        Write-Host "   Compiling $proto..." -ForegroundColor Gray
        
        $args = @(
            "--proto_path=$ProtoDir"
            "--ts_out=$TsOutputDir"
            "--ts_opt=optimize_code_size"
            "--ts_opt=long_type_string"
            "--ts_opt=generate_dependencies"
            $protoPath
        )
        
        if ($Verbose) {
            Write-Host "   Command: protoc $($args -join ' ')" -ForegroundColor DarkGray
        }
        
        try {
            & protoc @args
            Write-Host "   ✅ $proto compiled successfully" -ForegroundColor Green
        } catch {
            Write-Host "   ❌ Failed to compile $proto" -ForegroundColor Red
            Write-Host "   Error: $_" -ForegroundColor Red
        }
    }
    
    # Generate index.ts for easy imports
    $indexPath = Join-Path $TsOutputDir "index.ts"
    $indexContent = @"
// Generated TypeScript protobuf bindings
// Auto-generated by compile-protos.ps1

export * from './ingest';
export * from './embedding'; 
export * from './legal_services';

// Re-export common types for convenience
export type {
  Document,
  DocumentChunk,
  EntityMention,
  IngestRequest,
  IngestResponse,
  SearchRequest,
  SearchResponse
} from './ingest';

export type {
  EmbedRequest,
  EmbedResponse,
  BatchEmbedRequest,
  BatchEmbedResponse,
  ModelInfo,
  SimilarityRequest,
  SimilarityResponse
} from './embedding';

export type {
  ProcessDocumentRequest,
  ProcessDocumentResponse,
  ContextualQueryRequest,
  ContextualQueryResponse,
  CaseAnalysisRequest,
  CaseAnalysisResponse,
  EntityDiscoveryRequest,
  EntityDiscoveryResponse,
  SystemHealthRequest,
  SystemHealthResponse
} from './legal_services';
"@
    
    Set-Content -Path $indexPath -Value $indexContent -Encoding UTF8
    Write-Host "✅ Generated TypeScript index file" -ForegroundColor Green
}

function Compile-Go {
    Write-Host "🐹 Compiling Go bindings..." -ForegroundColor Blue
    
    foreach ($proto in $ProtoFiles) {
        $protoPath = Join-Path $ProtoDir $proto
        
        if (-not (Test-Path $protoPath)) {
            Write-Host "⚠️  Proto file not found: $protoPath" -ForegroundColor Yellow
            continue
        }
        
        Write-Host "   Compiling $proto..." -ForegroundColor Gray
        
        $args = @(
            "--proto_path=$ProtoDir"
            "--go_out=$GoOutputDir"
            "--go_opt=paths=source_relative"
            "--go-grpc_out=$GoOutputDir"
            "--go-grpc_opt=paths=source_relative"
            $protoPath
        )
        
        if ($Verbose) {
            Write-Host "   Command: protoc $($args -join ' ')" -ForegroundColor DarkGray
        }
        
        try {
            & protoc @args
            Write-Host "   ✅ $proto compiled successfully" -ForegroundColor Green
        } catch {
            Write-Host "   ❌ Failed to compile $proto" -ForegroundColor Red
            Write-Host "   Error: $_" -ForegroundColor Red
        }
    }
}

function Generate-ClientHelpers {
    Write-Host "🔧 Generating client helper files..." -ForegroundColor Blue
    
    # TypeScript gRPC client helper
    $tsClientPath = Join-Path $TsOutputDir "client.ts"
    $tsClientContent = @"
// Legal AI gRPC Client Helper
// Auto-generated by compile-protos.ps1

import { credentials } from '@grpc/grpc-js';
import { IngestServiceClient } from './ingest_grpc_pb';
import { EmbeddingServiceClient } from './embedding_grpc_pb';
import { LegalAIServiceClient } from './legal_services_grpc_pb';

export interface ClientConfig {
  embeddingServiceUrl?: string;
  ingestServiceUrl?: string;
  legalServiceUrl?: string;
  secure?: boolean;
  credentials?: any;
}

export class LegalAIClients {
  public embedding: EmbeddingServiceClient;
  public ingest: IngestServiceClient;
  public legal: LegalAIServiceClient;

  constructor(config: ClientConfig = {}) {
    const {
      embeddingServiceUrl = 'localhost:50051',
      ingestServiceUrl = 'localhost:50052',
      legalServiceUrl = 'localhost:50053',
      secure = false
    } = config;

    const creds = secure 
      ? credentials.createSsl()
      : credentials.createInsecure();

    this.embedding = new EmbeddingServiceClient(embeddingServiceUrl, creds);
    this.ingest = new IngestServiceClient(ingestServiceUrl, creds);
    this.legal = new LegalAIServiceClient(legalServiceUrl, creds);
  }

  async close(): Promise<void> {
    this.embedding.close();
    this.ingest.close();
    this.legal.close();
  }
}

export default LegalAIClients;
"@
    
    Set-Content -Path $tsClientPath -Value $tsClientContent -Encoding UTF8
    Write-Host "✅ Generated TypeScript client helper" -ForegroundColor Green
}

function Show-Summary {
    Write-Host "`n📊 Compilation Summary:" -ForegroundColor Cyan
    Write-Host "Proto files processed: $($ProtoFiles.Count)" -ForegroundColor White
    
    if (Test-Path $TsOutputDir) {
        $tsFiles = Get-ChildItem $TsOutputDir -Filter "*.ts" | Measure-Object
        Write-Host "TypeScript files generated: $($tsFiles.Count)" -ForegroundColor Green
    }
    
    if (Test-Path $GoOutputDir) {
        $goFiles = Get-ChildItem $GoOutputDir -Filter "*.go" | Measure-Object
        Write-Host "Go files generated: $($goFiles.Count)" -ForegroundColor Green
    }
    
    Write-Host "`n📍 Output locations:" -ForegroundColor Cyan
    Write-Host "TypeScript: $TsOutputDir" -ForegroundColor Gray
    Write-Host "Go: $GoOutputDir" -ForegroundColor Gray
    
    Write-Host "`n🎉 Proto compilation completed!" -ForegroundColor Green
}

# Main execution
try {
    Test-Prerequisites
    
    switch ($Target) {
        "all" {
            Compile-TypeScript
            Compile-Go
        }
        "typescript" {
            Compile-TypeScript
        }
        "go" {
            Compile-Go
        }
        default {
            Write-Host "❌ Invalid target: $Target" -ForegroundColor Red
            Write-Host "Valid options: all, typescript, go" -ForegroundColor Yellow
            exit 1
        }
    }
    
    Generate-ClientHelpers
    Show-Summary
    
} catch {
    Write-Host "❌ Proto compilation failed: $_" -ForegroundColor Red
    exit 1
}