-- Create indexes for efficient vector similarity search
CREATE INDEX IF NOT EXISTS idx_vectors_embedding_cosine 
ON vectors USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);

CREATE INDEX IF NOT EXISTS idx_vectors_embedding_l2 
ON vectors USING ivfflat (embedding vector_l2_ops) WITH (lists = 100);

CREATE INDEX IF NOT EXISTS idx_vectors_owner_type ON vectors (owner_type);
CREATE INDEX IF NOT EXISTS idx_vectors_owner_id ON vectors (owner_id);
CREATE INDEX IF NOT EXISTS idx_vectors_created_at ON vectors (created_at);

-- Unique constraint to prevent duplicates
CREATE UNIQUE INDEX IF NOT EXISTS idx_vectors_owner_unique 
ON vectors (owner_type, owner_id);

-- Function to update the updated_at timestamp
CREATE OR REPLACE FUNCTION update_vectors_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger to automatically update the updated_at column
CREATE TRIGGER vectors_updated_at_trigger
    BEFORE UPDATE ON vectors
    FOR EACH ROW
    EXECUTE FUNCTION update_vectors_updated_at();

