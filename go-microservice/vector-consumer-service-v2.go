// Start the enterprise service
func (s *EnterpriseVectorService) Start() error {
	// Set up signal handling for graceful shutdown
	signal.Notify(s.shutdown, os.Interrupt, syscall.SIGTERM)
	
	// Start gRPC server
	lis, err := net.Listen("tcp", fmt.Sprintf(":%d", s.config.GRPCPort))
	if err != nil {
		return fmt.Errorf("failed to listen on port %d: %w", s.config.GRPCPort, err)
	}
	
	grpcServer := grpc.NewServer(
		grpc.MaxRecvMsgSize(64*1024*1024), // 64MB max message size
		grpc.MaxSendMsgSize(64*1024*1024),
	)
	
	// Register services
	// pb.RegisterVectorServiceServer(grpcServer, s)
	grpc_health_v1.RegisterHealthServer(grpcServer, s.healthServer)
	reflection.Register(grpcServer)
	
	// Start message queue consumers
	for i := 0; i < s.config.MaxWorkers; i++ {
		s.wg.Add(1)
		go s.messageQueueWorker(i)
	}
	
	s.logger.WithFields(logrus.Fields{
		"grpc_port": s.config.GRPCPort,
		"workers": s.config.MaxWorkers,
	}).Info("Enterprise Vector Service started")
	
	// Start gRPC server in goroutine
	go func() {
		if err := grpcServer.Serve(lis); err != nil {
			s.logger.WithError(err).Fatal("gRPC server failed")
		}
	}()
	
	// Wait for shutdown signal
	<-s.shutdown
	s.logger.Info("Shutdown signal received")
	
	// Graceful shutdown
	grpcServer.GracefulStop()
	s.wg.Wait()
	
	return nil
}

// Message queue worker
func (s *EnterpriseVectorService) messageQueueWorker(workerID int) {
	defer s.wg.Done()
	
	msgs, err := s.rabbitChannel.Consume(
		s.config.QueueName,
		fmt.Sprintf("worker_%d", workerID),
		false, // manual ack
		false, // exclusive
		false, // no-local
		false, // no-wait
		nil,   // args
	)
	if err != nil {
		s.logger.WithError(err).Error("Failed to register consumer")
		return
	}
	
	for msg := range msgs {
		if err := s.processMessage(msg.Body); err != nil {
			s.logger.WithError(err).Error("Message processing failed")
			msg.Nack(false, true) // Requeue on failure
		} else {
			msg.Ack(false)
		}
	}
}

// Process individual message
func (s *EnterpriseVectorService) processMessage(body []byte) error {
	s.totalRequests.Inc()
	
	var job map[string]interface{}
	if err := json.Unmarshal(body, &job); err != nil {
		return fmt.Errorf("message unmarshal failed: %w", err)
	}
	
	jobType, ok := job["type"].(string)
	if !ok {
		return fmt.Errorf("invalid job type")
	}
	
	ctx := context.Background()
	
	switch jobType {
	case "similarity":
		return s.processSimilarityJob(ctx, job)
	case "embedding":
		return s.processEmbeddingJob(ctx, job)
	case "rotation":
		return s.processRotationJob(ctx, job)
	default:
		return fmt.Errorf("unknown job type: %s", jobType)
	}
}

// Process similarity job
func (s *EnterpriseVectorService) processSimilarityJob(ctx context.Context, job map[string]interface{}) error {
	// Extract vectors from job
	vectorAInterface, ok := job["vector_a"].([]interface{})
	if !ok {
		return fmt.Errorf("invalid vector_a")
	}
	
	vectorBInterface, ok := job["vector_b"].([]interface{})
	if !ok {
		return fmt.Errorf("invalid vector_b")
	}
	
	// Convert to float32 slices
	vectorA := make([]float32, len(vectorAInterface))
	for i, v := range vectorAInterface {
		if f, ok := v.(float64); ok {
			vectorA[i] = float32(f)
		}
	}
	
	vectorB := make([]float32, len(vectorBInterface))
	for i, v := range vectorBInterface {
		if f, ok := v.(float64); ok {
			vectorB[i] = float32(f)
		}
	}
	
	// Process with cuBLAS optimization
	result, err := s.processSimilarityWithCuBLAS(ctx, vectorA, vectorB)
	if err != nil {
		return err
	}
	
	s.logger.WithFields(logrus.Fields{
		"job_id": result.JobID,
		"similarity_score": result.SimilarityScore,
		"used_cublas": result.UsedCuBLAS,
	}).Info("Similarity job completed")
	
	return nil
}

